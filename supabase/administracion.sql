-- supabase/administracion.sql · Administración y moderación (pantalla pages/admin.html).
-- Se ejecuta en Supabase › SQL Editor DESPUÉS de esquema.sql. Se puede ejecutar más de una vez.
--
-- Qué hace:
-- · administradores: las cuentas que pueden moderar. Se agregan a mano aquí, en el SQL Editor (al final
--   del archivo está cómo). Nadie las puede leer ni cambiar desde la app.
-- · Bloquear una cuenta (usuarios.bloqueado): su perfil se ve como "Cuenta suspendida", sus reseñas, guías,
--   clips y comentarios dejan de verse para todos, y ya no puede publicar, comentar, reportar, escribir
--   mensajes, pedir amistad ni cambiar su perfil público. Sigue pudiendo entrar y ver la app.
-- · Ocultar una publicación (resenas.oculta, que ya usaban los reportes) con un motivo; aprobarla
--   (la vuelve a mostrar y descarta sus reportes) o borrarla. Borrar comentarios.
-- · Cada acción queda en el registro (moderacion) y la persona afectada recibe un aviso en la campana.
--
-- Seguridad: la página solo usa la llave publicable. Todo lo que hace un administrador pasa por las
-- funciones admin_… de abajo, que primero preguntan es_admin(): sin estar en administradores, la base
-- responde "Solo para administradores" aunque alguien copie la página. Lo oculto NO se abre con reglas
-- de lectura para administradores, para que la app normal (Comunidad, Inicio…) nunca lo muestre.

-- ============================================================================
-- 1. QUIÉN ES ADMINISTRADOR
-- ============================================================================
create table if not exists public.administradores (
  auth_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.administradores enable row level security;
revoke all on table public.administradores from anon, authenticated;

-- ¿La cuenta abierta es administradora? (la usan las funciones de abajo, el menú de la cuenta y la página)
create or replace function public.es_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select auth.uid() is not null and exists (select 1 from public.administradores where auth_id = auth.uid())
$$;
revoke all on function public.es_admin() from public;
grant execute on function public.es_admin() to anon, authenticated;

-- ============================================================================
-- 2. COLUMNAS Y TABLAS NUEVAS
-- ============================================================================
-- Bloqueo de cuentas. Todos pueden leer si una cuenta está bloqueada (la app muestra "Cuenta suspendida");
-- el motivo solo lo ve la propia persona (mi_bloqueo()) y los administradores.
alter table public.usuarios add column if not exists bloqueado boolean not null default false;
alter table public.usuarios add column if not exists bloqueado_motivo text check (char_length(bloqueado_motivo) <= 300);
alter table public.usuarios add column if not exists bloqueado_el timestamptz;
grant select (bloqueado) on table public.usuarios to anon, authenticated;

-- Por qué se ocultó una publicación (vacío si la ocultaron los reportes)
alter table public.resenas add column if not exists motivo_oculta text check (char_length(motivo_oculta) <= 300);

-- Registro de moderación: qué hizo cada administrador. Sin claves foráneas hacia lo afectado,
-- para que quede aunque la publicación o la cuenta ya no existan.
create table if not exists public.moderacion (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  admin_id uuid references auth.users (id) on delete set null,
  accion text not null check (accion in ('ocultar', 'aprobar', 'borrar_publicacion', 'borrar_comentario', 'bloquear', 'desbloquear')),
  usuario_id bigint,     -- la cuenta afectada (autora de lo moderado)
  resena_id bigint,
  comentario_id bigint,
  motivo text check (char_length(motivo) <= 300),
  detalle text           -- copia corta de lo borrado (para saber qué era)
);
alter table public.moderacion enable row level security;
revoke all on table public.moderacion from anon, authenticated;

-- Los avisos de la campana ahora también avisan de moderación
alter table public.notificaciones drop constraint if exists notificaciones_tipo_check;
alter table public.notificaciones add constraint notificaciones_tipo_check
  check (tipo in ('voto_util', 'cierre_inscripciones', 'mensaje', 'moderacion'));

-- ============================================================================
-- 3. AYUDAS PARA LAS REGLAS
-- ============================================================================
-- ¿Esta cuenta (id de usuarios) está bloqueada?
create or replace function public.usuario_bloqueado(p_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select bloqueado from public.usuarios where id = p_id), false)
$$;
-- ¿La cuenta abierta está bloqueada?
create or replace function public.estoy_bloqueado() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select bloqueado from public.usuarios where auth_id = auth.uid()), false)
$$;
-- Lo que la propia persona puede saber de su bloqueo (la app lo muestra arriba de cada página)
create or replace function public.mi_bloqueo() returns json
language sql stable security definer set search_path = public as $$
  select json_build_object('bloqueado', bloqueado, 'motivo', bloqueado_motivo, 'desde', bloqueado_el)
  from public.usuarios where auth_id = auth.uid() and bloqueado
$$;
revoke all on function public.usuario_bloqueado(bigint) from public;
revoke all on function public.estoy_bloqueado() from public;
revoke all on function public.mi_bloqueo() from public;
grant execute on function public.usuario_bloqueado(bigint) to anon, authenticated;
grant execute on function public.estoy_bloqueado() to anon, authenticated;
grant execute on function public.mi_bloqueo() to authenticated;

-- ============================================================================
-- 4. REGLAS QUE CAMBIAN CON EL BLOQUEO
--    (son las mismas de esquema.sql, con una condición más; se reemplazan por nombre)
-- ============================================================================
-- Reseñas, guías y clips: lo de una cuenta bloqueada no lo ve nadie más (su autor sí, como lo oculto)
drop policy if exists "resenas: ver publicadas y borradores propios" on public.resenas;
create policy "resenas: ver publicadas y borradores propios" on public.resenas for select to anon, authenticated
  using ((estado = 'publicada' and not oculta and not public.usuario_bloqueado(usuario_id))
         or usuario_id = (select public.mi_usuario_id()));
drop policy if exists "resenas: agregar las propias" on public.resenas;
create policy "resenas: agregar las propias" on public.resenas for insert to authenticated
  with check (usuario_id = (select public.mi_usuario_id()) and not (select public.estoy_bloqueado())
    and (clip_archivo is null or split_part(clip_archivo, '/', 1) = (select auth.uid())::text));
drop policy if exists "resenas: cambiar las propias" on public.resenas;
create policy "resenas: cambiar las propias" on public.resenas for update to authenticated
  using (usuario_id = (select public.mi_usuario_id()) and not (select public.estoy_bloqueado()))
  with check (usuario_id = (select public.mi_usuario_id()) and not (select public.estoy_bloqueado()));

-- Comentarios: los de cuentas bloqueadas y los de publicaciones que no se ven, ocultos; bloqueado no comenta
drop policy if exists "comentarios: ver" on public.comentarios;
create policy "comentarios: ver" on public.comentarios for select to anon, authenticated
  using (not public.usuario_bloqueado(usuario_id) and exists (select 1 from public.resenas r where r.id = resena_id));
drop policy if exists "comentarios: agregar los propios" on public.comentarios;
create policy "comentarios: agregar los propios" on public.comentarios for insert to authenticated
  with check (usuario_id = (select public.mi_usuario_id()) and not (select public.estoy_bloqueado()));

-- Reportes, solicitudes de amistad y mensajes: una cuenta bloqueada no los envía
drop policy if exists "reportes: agregar los propios" on public.reportes;
create policy "reportes: agregar los propios" on public.reportes for insert to authenticated
  with check (usuario_id = (select public.mi_usuario_id()) and not (select public.estoy_bloqueado())
    and exists (select 1 from public.resenas r where r.id = resena_id and r.usuario_id <> (select public.mi_usuario_id())));
drop policy if exists "amigos: enviar solicitud" on public.amigos;
create policy "amigos: enviar solicitud" on public.amigos for insert to authenticated
  with check (usuario_id = (select public.mi_usuario_id()) and estado = 'pendiente' and not (select public.estoy_bloqueado()));
drop policy if exists "mensajes: escribir a un amigo" on public.mensajes;
create policy "mensajes: escribir a un amigo" on public.mensajes for insert to authenticated
  with check (
    de_id = (select public.mi_usuario_id()) and not leido and not (select public.estoy_bloqueado())
    and exists (
      select 1 from public.amigos a
      where a.estado = 'aceptada'
        and least(a.usuario_id, a.amigo_id) = least(de_id, para_id)
        and greatest(a.usuario_id, a.amigo_id) = greatest(de_id, para_id)
    )
  );

-- Perfil público: una cuenta bloqueada no cambia su @, nombre, sobre mí, juego actual, color ni foto.
-- Lo demás (por ejemplo, la última conexión) sí, para que la app siga funcionando.
create or replace function public.antes_de_cambiar_usuario() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if old.bloqueado and auth.uid() = old.auth_id and (
       new.usuario is distinct from old.usuario or new.nombre is distinct from old.nombre
    or new.iniciales is distinct from old.iniciales or new.sobre_mi is distinct from old.sobre_mi
    or new.jugando_ahora is distinct from old.jugando_ahora or new.color is distinct from old.color
    or new.foto is distinct from old.foto) then
    raise exception 'Tu cuenta está suspendida: no puedes cambiar tu perfil' using errcode = '42501';
  end if;
  return new;
end $$;
drop trigger if exists antes_de_cambiar_usuario on public.usuarios;
create trigger antes_de_cambiar_usuario before update on public.usuarios
  for each row execute function public.antes_de_cambiar_usuario();
revoke all on function public.antes_de_cambiar_usuario() from public, anon, authenticated;

-- Videos de clips: un administrador puede borrar el archivo al borrar la publicación
drop policy if exists "clips: admin borra" on storage.objects;
create policy "clips: admin borra" on storage.objects for delete to authenticated
  using (bucket_id = 'clips' and (select public.es_admin()));

-- ============================================================================
-- 5. FUNCIONES DE LA PÁGINA DE ADMINISTRACIÓN (todas empiezan preguntando es_admin())
-- ============================================================================
create or replace function public.admin_exigir() returns void
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.es_admin() then
    raise exception 'Solo para administradores' using errcode = '42501';
  end if;
end $$;

-- Aviso en la campana de la persona afectada
create or replace function public.admin_avisar(p_usuario bigint, p_texto text, p_enlace text) returns void
language sql security definer set search_path = public as $$
  insert into public.notificaciones (usuario_id, tipo, texto, enlace)
  select p_usuario, 'moderacion', left(p_texto, 300), p_enlace
  where exists (select 1 from public.usuarios where id = p_usuario)
$$;

-- Nombre de una publicación para los avisos ("tu reseña", "tu guía", "tu clip")
create or replace function public.admin_nombre_tipo(p_tipo text) returns text
language sql immutable as $$
  select case p_tipo when 'guia' then 'guía' when 'clip' then 'clip' else 'reseña' end
$$;

-- Números de arriba de la página
create or replace function public.admin_resumen() returns json
language plpgsql stable security definer set search_path = public as $$
begin
  perform public.admin_exigir();
  return json_build_object(
    'usuarios', (select count(*) from public.usuarios where auth_id is not null),
    'bloqueados', (select count(*) from public.usuarios where bloqueado),
    'resenas', (select count(*) from public.resenas where tipo = 'resena' and estado = 'publicada'),
    'guias', (select count(*) from public.resenas where tipo = 'guia' and estado = 'publicada'),
    'clips', (select count(*) from public.resenas where tipo = 'clip' and estado = 'publicada'),
    'ocultas', (select count(*) from public.resenas where oculta),
    'reportadas', (select count(distinct p.resena_id) from public.reportes p join public.resenas r on r.id = p.resena_id where not r.oculta),
    'por_revisar', (select count(*) from public.resenas r where r.oculta or exists (select 1 from public.reportes p where p.resena_id = r.id))
  );
end $$;

-- Publicaciones (reseñas, guías y clips), con su autor y cuántos reportes y comentarios tienen.
-- p_tipo: 'resena', 'guia', 'clip' o vacío (todas). p_filtro: 'revisar' (ocultas o reportadas), 'visibles',
-- 'ocultas', 'reportadas', 'borradores' o 'todas'. p_buscar: texto en título, texto o @ del autor.
-- p_autor: solo las de esa cuenta (id de usuarios).
create or replace function public.admin_publicaciones(
  p_tipo text default null, p_filtro text default 'todas', p_buscar text default null,
  p_autor bigint default null, p_limite integer default 30, p_desde integer default 0
) returns json
language plpgsql stable security definer set search_path = public as $$
declare
  resultado json;
  buscado text := nullif(btrim(coalesce(p_buscar, '')), '');
begin
  perform public.admin_exigir();
  select coalesce(json_agg(x), '[]'::json) into resultado from (
    select r.id, r.tipo, r.estado, r.titulo, left(r.texto, 5000) as texto, r.calificacion, r.dificultad, r.horas,
      r.juego_igdb, r.fecha, r.editada, r.spoiler, r.oculta, r.motivo_oculta,
      r.clip_twitch, r.clip_archivo, r.clip_miniatura,
      u.id as autor_id, u.usuario as autor, u.nombre as autor_nombre, u.bloqueado as autor_bloqueado,
      (select count(*) from public.reportes p where p.resena_id = r.id) as reportes,
      (select count(*) from public.comentarios c where c.resena_id = r.id) as comentarios
    from public.resenas r
    join public.usuarios u on u.id = r.usuario_id
    where (nullif(p_tipo, '') is null or r.tipo = p_tipo)
      and (p_autor is null or r.usuario_id = p_autor)
      and case coalesce(p_filtro, 'todas')
            when 'revisar' then r.oculta or exists (select 1 from public.reportes p where p.resena_id = r.id)
            when 'visibles' then r.estado = 'publicada' and not r.oculta
            when 'ocultas' then r.oculta
            when 'reportadas' then exists (select 1 from public.reportes p where p.resena_id = r.id)
            when 'borradores' then r.estado = 'borrador'
            else true end
      and (buscado is null or r.titulo ilike '%' || buscado || '%' or r.texto ilike '%' || buscado || '%'
           or u.usuario ilike '%' || buscado || '%' or u.nombre ilike '%' || buscado || '%')
    order by (case when p_filtro in ('revisar', 'reportadas') then (select count(*) from public.reportes p where p.resena_id = r.id) else 0 end) desc,
      r.fecha desc, r.id desc
    limit least(greatest(coalesce(p_limite, 30), 1), 100) offset greatest(coalesce(p_desde, 0), 0)
  ) x;
  return resultado;
end $$;

-- Los reportes de una publicación (quién y por qué)
create or replace function public.admin_reportes(p_resena bigint) returns json
language plpgsql stable security definer set search_path = public as $$
declare resultado json;
begin
  perform public.admin_exigir();
  select coalesce(json_agg(x order by x.fecha desc), '[]'::json) into resultado from (
    select p.id, p.created_at as fecha, p.motivo, u.usuario
    from public.reportes p join public.usuarios u on u.id = p.usuario_id
    where p.resena_id = p_resena
  ) x;
  return resultado;
end $$;

-- Los comentarios de una publicación (también los de cuentas bloqueadas)
create or replace function public.admin_comentarios(p_resena bigint) returns json
language plpgsql stable security definer set search_path = public as $$
declare resultado json;
begin
  perform public.admin_exigir();
  select coalesce(json_agg(x order by x.fecha), '[]'::json) into resultado from (
    select c.id, c.fecha, c.texto, u.id as autor_id, u.usuario as autor, u.bloqueado as autor_bloqueado
    from public.comentarios c join public.usuarios u on u.id = c.usuario_id
    where c.resena_id = p_resena
  ) x;
  return resultado;
end $$;

-- Perfiles: p_filtro 'todos', 'bloqueados' o 'reportados' (con publicaciones reportadas). p_buscar: @, nombre o correo.
create or replace function public.admin_usuarios(
  p_buscar text default null, p_filtro text default 'todos', p_limite integer default 30, p_desde integer default 0
) returns json
language plpgsql stable security definer set search_path = public as $$
declare
  resultado json;
  buscado text := nullif(btrim(coalesce(p_buscar, '')), '');
begin
  perform public.admin_exigir();
  select coalesce(json_agg(x), '[]'::json) into resultado from (
    select u.id, u.usuario, u.nombre, u.iniciales, u.foto, u.sobre_mi, u.nivel, u.forma_de_entrar, u.invitado,
      u.miembro_desde, u.ultima_conexion, u.bloqueado, u.bloqueado_motivo, u.bloqueado_el,
      a.email as correo,
      exists (select 1 from public.administradores ad where ad.auth_id = u.auth_id) as es_admin,
      (select count(*) from public.resenas r where r.usuario_id = u.id and r.estado = 'publicada') as publicaciones,
      (select count(*) from public.comentarios c where c.usuario_id = u.id) as comentarios,
      (select count(*) from public.reportes p join public.resenas r on r.id = p.resena_id where r.usuario_id = u.id) as reportes
    from public.usuarios u
    left join auth.users a on a.id = u.auth_id
    where u.auth_id is not null
      and case coalesce(p_filtro, 'todos')
            when 'bloqueados' then u.bloqueado
            when 'reportados' then exists (select 1 from public.reportes p join public.resenas r on r.id = p.resena_id where r.usuario_id = u.id)
            else true end
      and (buscado is null or u.usuario ilike '%' || buscado || '%' or u.nombre ilike '%' || buscado || '%'
           or a.email ilike '%' || buscado || '%')
    order by u.bloqueado desc, u.created_at desc, u.id desc
    limit least(greatest(coalesce(p_limite, 30), 1), 100) offset greatest(coalesce(p_desde, 0), 0)
  ) x;
  return resultado;
end $$;

-- Registro de moderación (lo más nuevo primero)
create or replace function public.admin_registro(p_limite integer default 50, p_desde integer default 0) returns json
language plpgsql stable security definer set search_path = public as $$
declare resultado json;
begin
  perform public.admin_exigir();
  select coalesce(json_agg(x), '[]'::json) into resultado from (
    select m.id, m.created_at as fecha, m.accion, m.motivo, m.detalle, m.resena_id, m.comentario_id,
      a.email as admin, u.usuario
    from public.moderacion m
    left join auth.users a on a.id = m.admin_id
    left join public.usuarios u on u.id = m.usuario_id
    order by m.created_at desc, m.id desc
    limit least(greatest(coalesce(p_limite, 50), 1), 200) offset greatest(coalesce(p_desde, 0), 0)
  ) x;
  return resultado;
end $$;

-- Ocultar una publicación (deja de verse en toda la app; su autor la sigue viendo con el motivo)
create or replace function public.admin_ocultar_publicacion(p_id bigint, p_motivo text) returns void
language plpgsql security definer set search_path = public as $$
declare r record;
begin
  perform public.admin_exigir();
  update public.resenas set oculta = true, motivo_oculta = nullif(left(btrim(coalesce(p_motivo, '')), 300), '')
    where id = p_id returning id, usuario_id, tipo into r;
  if r.id is null then raise exception 'La publicación ya no existe' using errcode = 'P0002'; end if;
  insert into public.moderacion (admin_id, accion, usuario_id, resena_id, motivo)
    values (auth.uid(), 'ocultar', r.usuario_id, p_id, nullif(left(btrim(coalesce(p_motivo, '')), 300), ''));
  perform public.admin_avisar(r.usuario_id,
    'Moderación ocultó tu ' || public.admin_nombre_tipo(r.tipo) || coalesce(': ' || nullif(btrim(p_motivo), ''), '.'),
    'historial-resenas.html');
end $$;

-- Aprobar: la vuelve a mostrar y descarta sus reportes (así un reporte más no la vuelve a ocultar)
create or replace function public.admin_aprobar_publicacion(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare r record;
begin
  perform public.admin_exigir();
  update public.resenas set oculta = false, motivo_oculta = null where id = p_id returning id, usuario_id, tipo, estado into r;
  if r.id is null then raise exception 'La publicación ya no existe' using errcode = 'P0002'; end if;
  delete from public.reportes where resena_id = p_id;
  insert into public.moderacion (admin_id, accion, usuario_id, resena_id) values (auth.uid(), 'aprobar', r.usuario_id, p_id);
end $$;

-- Borrar una publicación (con sus comentarios, votos y reportes). El video de un clip lo borra la página.
create or replace function public.admin_borrar_publicacion(p_id bigint, p_motivo text) returns void
language plpgsql security definer set search_path = public as $$
declare r record;
begin
  perform public.admin_exigir();
  select id, usuario_id, tipo, titulo, texto into r from public.resenas where id = p_id;
  if r.id is null then raise exception 'La publicación ya no existe' using errcode = 'P0002'; end if;
  insert into public.moderacion (admin_id, accion, usuario_id, resena_id, motivo, detalle)
    values (auth.uid(), 'borrar_publicacion', r.usuario_id, p_id, nullif(left(btrim(coalesce(p_motivo, '')), 300), ''),
            left(coalesce(r.titulo || ' · ', '') || coalesce(r.texto, ''), 200));
  delete from public.resenas where id = p_id;
  perform public.admin_avisar(r.usuario_id,
    'Moderación borró tu ' || public.admin_nombre_tipo(r.tipo) || coalesce(': ' || nullif(btrim(p_motivo), ''), '.'),
    'historial-resenas.html');
end $$;

-- Borrar un comentario
create or replace function public.admin_borrar_comentario(p_id bigint, p_motivo text) returns void
language plpgsql security definer set search_path = public as $$
declare c record;
begin
  perform public.admin_exigir();
  select id, usuario_id, resena_id, texto into c from public.comentarios where id = p_id;
  if c.id is null then raise exception 'El comentario ya no existe' using errcode = 'P0002'; end if;
  insert into public.moderacion (admin_id, accion, usuario_id, resena_id, comentario_id, motivo, detalle)
    values (auth.uid(), 'borrar_comentario', c.usuario_id, c.resena_id, p_id,
            nullif(left(btrim(coalesce(p_motivo, '')), 300), ''), left(c.texto, 200));
  delete from public.comentarios where id = p_id;
  perform public.admin_avisar(c.usuario_id,
    'Moderación borró un comentario tuyo' || coalesce(': ' || nullif(btrim(p_motivo), ''), '.'),
    'detalle-resena.html?id=' || c.resena_id);
end $$;

-- Bloquear o desbloquear una cuenta (nunca la propia ni la de otro administrador)
create or replace function public.admin_bloquear_usuario(p_id bigint, p_bloquear boolean, p_motivo text) returns void
language plpgsql security definer set search_path = public as $$
declare u record;
begin
  perform public.admin_exigir();
  select id, auth_id, bloqueado into u from public.usuarios where id = p_id;
  if u.id is null then raise exception 'La cuenta ya no existe' using errcode = 'P0002'; end if;
  if p_bloquear and (u.auth_id = auth.uid() or exists (select 1 from public.administradores where auth_id = u.auth_id)) then
    raise exception 'No se puede bloquear a un administrador' using errcode = '42501';
  end if;
  update public.usuarios set
