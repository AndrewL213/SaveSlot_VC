  for each row execute function public.al_votar_util();

-- Avisos de cierre: a quien se inscribió a un evento que cierra inscripciones en las próximas 24 horas
-- (una vez por evento). Hay que ejecutarla cada cierto tiempo: por ejemplo con un cron de Vercel o de Supabase.
create or replace function public.crear_avisos_de_cierre() returns integer
language plpgsql security definer set search_path = public as $$
declare
  creados integer;
begin
  insert into public.notificaciones (usuario_id, tipo, texto, enlace)
  select i.usuario_id, 'cierre_inscripciones', e.titulo || ' cierra inscripciones pronto.', 'detalle-evento.html?id=' || e.slug
  from public.inscripciones i join public.eventos e on e.id = i.evento_id
  where e.cierre_inscripciones between now() and now() + interval '24 hours'
    and not exists (
      select 1 from public.notificaciones n
      where n.usuario_id = i.usuario_id and n.tipo = 'cierre_inscripciones' and n.enlace = 'detalle-evento.html?id=' || e.slug
    );
  get diagnostics creados = row_count;
  return creados;
end $$;

