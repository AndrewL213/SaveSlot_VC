-- diario: los juegos que cada persona registró
create table if not exists public.diario (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  usuario_id bigint not null references public.usuarios (id) on delete cascade,
  juego_igdb integer not null,
  fecha date not null default current_date,
  estado text not null check (estado in ('Terminado', 'Rejugado', 'En progreso', 'Abandonado')),
  horas numeric check (horas >= 0),
  calificacion integer check (calificacion between 1 and 10),
  me_gusta boolean not null default false,
  tiene_resena boolean not null default false
