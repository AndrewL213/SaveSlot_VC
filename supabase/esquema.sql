-- una sola fila por pareja, sin importar quién la envió
create unique index if not exists amigos_una_por_pareja on public.amigos (least(usuario_id, amigo_id), greatest(usuario_id, amigo_id));

-- inscripciones: quién se inscribió a cada evento (una por persona y evento)
