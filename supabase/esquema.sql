-- supabase/esquema.sql · Tablas, reglas de acceso y datos de ejemplo de SaveSlot (sección Datos de spec.md).
-- Se ejecuta en Supabase › SQL Editor. Se puede ejecutar más de una vez: no borra nada ni repite filas.
-- No toca las tablas que ya existen: juegos (supabase/juegos.sql) y usuarios_steam (supabase/usuarios_steam.sql).
--
-- Cómo se protegen los datos:
-- · Sin sesión (anon) solo se ve lo público. Para agregar, cambiar o borrar hace falta sesión (authenticated,
--   también la de invitado) y cada persona solo toca lo suyo: mi_usuario_id() dice qué fila de usuarios es la suya.
-- · Nivel, XP, misiones cumplidas, cupos ocupados y notificaciones solo los cambia la base (reglas al final).
-- · El servidor (api/ en Vercel, con la llave secreta) no pasa por estas reglas: así escribe traducciones.
-- · Primero se le quitan a cada tabla los permisos que Supabase da por defecto y luego se dan solo los necesarios.

-- ============================================================================
-- 1. TABLAS
-- ============================================================================

-- usuarios: el perfil público de cada cuenta (el correo y la contraseña quedan solo en Supabase Auth)
create table if not exists public.usuarios (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  auth_id uuid unique references auth.users (id) on delete cascade,        -- la cuenta; vacío en los usuarios de ejemplo
  usuario text not null unique check (usuario ~ '^[A-Za-z0-9._]{3,20}$'), -- el @
  nombre text not null,
  iniciales text not null,
  sobre_mi text,
  jugando_ahora text,                                                       -- slug de IGDB, steam-<número> o "steam" (automático)
  miembro_desde date not null default current_date,
  nivel integer not null default 1 check (nivel >= 1),                      -- lo cambia la base
  xp integer not null default 0 check (xp >= 0),                            -- XP dentro del nivel; lo cambia la base
  color text check (color ~ '^#[0-9A-Fa-f]{6}$'),
  forma_de_entrar text not null default 'correo' check (forma_de_entrar in ('correo', 'google', 'discord', 'twitch', 'steam')),
  invitado boolean not null default false
);

-- usuarios_favoritos: los 4 juegos favoritos de cada persona (tabla aparte porque son varios por persona)
create table if not exists public.usuarios_favoritos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  usuario_id bigint not null references public.usuarios (id) on delete cascade,
  juego text not null,                                                      -- slug de IGDB o steam-<número>
  orden integer not null check (orden between 1 and 4),
  unique (usuario_id, orden)
);

-- usuarios_generos: los géneros favoritos de cada persona (varios por persona)
create table if not exists public.usuarios_generos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  usuario_id bigint not null references public.usuarios (id) on delete cascade,
  genero text not null check (genero in ('Aventura', 'RPG', 'Acción', 'Terror', 'Shooter', 'Deportes', 'Roguelike', 'Carreras', 'Estrategia', 'Metroidvania', 'Pelea', 'Plataformas', 'Puzzle', 'Simulación', 'Supervivencia')),
  unique (usuario_id, genero)
);

-- lista_deseos: la lista de deseos de SaveSlot de cada persona (varios juegos por persona; la ven todos)
create table if not exists public.lista_deseos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  usuario_id bigint not null references public.usuarios (id) on delete cascade,
  juego text not null,                                                      -- slug de IGDB
  unique (usuario_id, juego)
);

-- insignias: las insignias de cada persona ("Fundador beta"…); las pone el equipo o la base
create table if not exists public.insignias (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  usuario_id bigint not null references public.usuarios (id) on delete cascade,
  texto text not null,
  unique (usuario_id, texto)
);

-- cuentas_vinculadas: las cuentas de juego que cada persona vinculó (Steam real, Xbox simulada)
create table if not exists public.cuentas_vinculadas (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  usuario_id bigint not null references public.usuarios (id) on delete cascade,
  plataforma text not null check (plataforma in ('steam', 'xbox')),
  nombre text not null,
  estado text not null default 'pendiente' check (estado in ('verificada', 'pendiente')),
  unique (usuario_id, plataforma)
);

-- misiones: las formas de ganar XP (ventana "Cómo ganar XP")
create table if not exists public.misiones (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  clave text not null unique,                                               -- publicar, vincular, torneo, amistad
  texto text not null,
  xp integer not null check (xp > 0),
  repetible boolean not null                                                -- si se gana cada vez o una vez por cosa
);

-- misiones_cumplidas: qué misión cumplió cada persona (la llena la base y suma el XP)
create table if not exists public.misiones_cumplidas (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  usuario_id bigint not null references public.usuarios (id) on delete cascade,
  mision_id bigint not null references public.misiones (id) on delete cascade,
  referencia text not null default '',                                      -- la reseña, cuenta, evento o amistad (no se cuenta dos veces)
  fecha timestamptz not null default now(),
  unique (usuario_id, mision_id, referencia)
);

-- eventos: torneos y sorteos (los crea el equipo; los cupos ocupados los cambia la base)
create table if not exists public.eventos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  slug text not null unique,                                                -- va en la dirección: detalle-evento.html?id=copa-2v2
  tipo text not null check (tipo in ('torneo', 'sorteo')),
  juego_igdb integer,                                                       -- número del juego en IGDB
  titulo text not null,
  descripcion text not null,
  fecha_hora timestamptz not null,
  cierre_inscripciones timestamptz,
  organizador text not null,
  tipo_organizador text not null check (tipo_organizador in ('Marcas y organizadores', 'Desarrolladoras oficiales', 'SaveSlot')),
  cupos_ocupados integer not null default 0 check (cupos_ocupados >= 0),
  cupos_maximos integer check (cupos_maximos > 0),
  costo text not null,
  gratis boolean not null,
  xp_para_entrar integer check (xp_para_entrar >= 0),                      -- solo sorteos
  premio text not null,
  ganador_id bigint references public.usuarios (id) on delete set null,     -- solo sorteos (si se borra la cuenta, el evento queda sin ganador)
  dias_para_reclamar integer check (dias_para_reclamar > 0),               -- solo sorteos
  color text check (color ~ '^#[0-9A-Fa-f]{6}$'),
  destacado boolean not null default false                                  -- el "evento del mes" de Inicio
);

-- eventos_cronograma: los pasos de cada evento con su cuándo (varios por evento)
create table if not exists public.eventos_cronograma (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  evento_id bigint not null references public.eventos (id) on delete cascade,
  paso text not null,
  cuando text not null,
  orden integer not null,
  unique (evento_id, orden)
);

-- eventos_reglas: las reglas de cada evento (varias por evento)
create table if not exists public.eventos_reglas (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  evento_id bigint not null references public.eventos (id) on delete cascade,
  texto text not null,
  orden integer not null,
  unique (evento_id, orden)
);

-- resenas: reseñas y guías publicadas, y los borradores (los borradores solo los ve su autor)
create table if not exists public.resenas (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  usuario_id bigint not null references public.usuarios (id) on delete cascade, -- el autor
  juego_igdb integer not null,
  tipo text not null check (tipo in ('resena', 'guia')),
  estado text not null default 'borrador' check (estado in ('publicada', 'borrador')),
  titulo text,
  texto text,
  calificacion integer check (calificacion between 1 and 10),
  dificultad integer check (dificultad between 1 and 10),
  horas numeric check (horas >= 0),
  estado_partida text check (estado_partida in ('Terminado', 'Rejugado', 'En progreso', 'Abandonado')),
  minutos_lectura integer check (minutos_lectura > 0),                      -- solo guías
  spoiler boolean not null default false,
  editada boolean not null default false,
  fecha timestamptz not null default now(),
  -- una reseña publicada necesita 50 caracteres o más
  check (estado <> 'publicada' or tipo <> 'resena' or char_length(texto) >= 50)
);
-- un borrador por persona y juego
create unique index if not exists resenas_un_borrador on public.resenas (usuario_id, juego_igdb) where estado = 'borrador';

-- votos_util: quién marcó una reseña como útil (uno por persona y reseña)
create table if not exists public.votos_util (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  usuario_id bigint not null references public.usuarios (id) on delete cascade,
  resena_id bigint not null references public.resenas (id) on delete cascade,
  fecha timestamptz not null default now(),
  unique (usuario_id, resena_id)
);

-- me_gusta_resenas: a quién le gusta una reseña (uno por persona y reseña)
create table if not exists public.me_gusta_resenas (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  usuario_id bigint not null references public.usuarios (id) on delete cascade,
  resena_id bigint not null references public.resenas (id) on delete cascade,
  fecha timestamptz not null default now(),
  unique (usuario_id, resena_id)
