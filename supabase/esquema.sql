-- ============================================================================
-- 2. QUIÉN SOY: la fila de usuarios de la cuenta con sesión abierta (vacío sin sesión)
-- ============================================================================
create or replace function public.mi_usuario_id() returns bigint
language sql stable security definer set search_path = public as $$
  select id from public.usuarios where auth_id = auth.uid()
$$;
revoke all on function public.mi_usuario_id() from public;
grant execute on function public.mi_usuario_id() to anon, authenticated;

