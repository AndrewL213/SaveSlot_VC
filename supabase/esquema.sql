-- Suma (o resta) XP; cada 1.500 XP se sube un nivel y el XP vuelve a contar desde el resto
create or replace function public.sumar_xp(p_usuario bigint, p_cantidad integer) returns void
language plpgsql security definer set search_path = public as $$
begin
  update public.usuarios set xp = xp + p_cantidad where id = p_usuario;
  update public.usuarios set nivel = nivel + xp / 1500, xp = xp % 1500 where id = p_usuario and xp >= 1500;
end $$;

-- Anota una misión cumplida (una sola vez por referencia) y suma su XP
create or replace function public.cumplir_mision(p_usuario bigint, p_clave text, p_referencia text) returns void
language plpgsql security definer set search_path = public as $$
declare
  m public.misiones;
  filas integer;
begin
  select * into m from public.misiones where clave = p_clave;
  if not found then return; end if;
  insert into public.misiones_cumplidas (usuario_id, mision_id, referencia)
  values (p_usuario, m.id, coalesce(p_referencia, ''))
  on conflict (usuario_id, mision_id, referencia) do nothing;
  get diagnostics filas = row_count;
  if filas > 0 then perform public.sumar_xp(p_usuario, m.xp); end if;
end $$;

-- Publicar una reseña o guía: misión "publicar" (+50 XP), una vez por reseña
create or replace function public.al_publicar_resena() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.estado = 'publicada' and (tg_op = 'INSERT' or old.estado <> 'publicada') then
    perform public.cumplir_mision(new.usuario_id, 'publicar', 'resena:' || new.id);
  end if;
  return new;
end $$;
drop trigger if exists al_publicar_resena on public.resenas;
create trigger al_publicar_resena after insert or update of estado on public.resenas
  for each row execute function public.al_publicar_resena();

