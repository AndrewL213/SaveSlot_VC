-- supabase/esquema.sql · Tablas, reglas de acceso y datos de ejemplo de SaveSlot (sección Datos de spec.md).
-- Se ejecuta en Supabase › SQL Editor. Se puede ejecutar más de una vez: no borra nada ni repite filas.
-- No toca las tablas que ya existen: juegos (supabase/juegos.sql) y usuarios_steam (supabase/usuarios_steam.sql).
--
-- Cómo se protegen los datos:
-- · Sin sesión (anon) solo se ve lo público. Para agregar, cambiar o borrar hace falta sesión (authenticated,
--   también la de invitado) y cada persona solo toca lo suyo: mi_usuario_id() dice qué fila de usuarios es la suya.
-- · Nivel, XP, misiones cumplidas, cupos ocupados y notificaciones solo los cambia la base (reglas al final).
-- · El servidor (api/ en Vercel, con la llave secreta) no pasa por estas reglas: así escribe traducciones.
-- · Primero se le quitan a cada tabla los permisos que Supabase da por defecto y luego se dan solo los necesarios.

