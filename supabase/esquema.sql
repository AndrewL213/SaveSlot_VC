-- resenas: reseñas y guías publicadas, y los borradores (los borradores solo los ve su autor)
create table if not exists public.resenas (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  usuario_id bigint not null references public.usuarios (id) on delete cascade, -- el autor
  juego_igdb integer not null,
  tipo text not null check (tipo in ('resena', 'guia')),
  estado text not null default 'borrador' check (estado in ('publicada', 'borrador')),
  titulo text,
  texto text,
  calificacion integer check (calificacion between 1 and 10),
  dificultad integer check (dificultad between 1 and 10),
  horas numeric check (horas >= 0),
  estado_partida text check (estado_partida in ('Terminado', 'Rejugado', 'En progreso', 'Abandonado')),
  minutos_lectura integer check (minutos_lectura > 0),                      -- solo guías
  spoiler boolean not null default false,
  editada boolean not null default false,
  fecha timestamptz not null default now(),
  -- una reseña publicada necesita 50 caracteres o más
  check (estado <> 'publicada' or tipo <> 'resena' or char_length(texto) >= 50)
);
-- un borrador por persona y juego
create unique index if not exists resenas_un_borrador on public.resenas (usuario_id, juego_igdb) where estado = 'borrador';

