-- Antes de inscribirse: revisa que no haya cerrado, que queden cupos y, en un sorteo con XP, que alcance el XP (y lo descuenta)
create or replace function public.antes_de_inscribirse() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  e public.eventos;
  mi_xp integer;
begin
  select * into e from public.eventos where id = new.evento_id for update;
  -- Inscripciones cerradas: pasó el cierre (o, si no tiene cierre, la fecha del evento)
  if coalesce(e.cierre_inscripciones, e.fecha_hora) < now() then
    raise exception 'Las inscripciones de este evento ya cerraron';
  end if;
  if e.cupos_maximos is not null and e.cupos_ocupados >= e.cupos_maximos then
    raise exception 'No quedan cupos en este evento';
  end if;
  if e.tipo = 'sorteo' and new.forma = 'xp' and coalesce(e.xp_para_entrar, 0) > 0 then
    select xp into mi_xp from public.usuarios where id = new.usuario_id for update;
    if mi_xp < e.xp_para_entrar then
      raise exception 'No tienes XP suficiente: necesitas % XP', e.xp_para_entrar;
    end if;
    update public.usuarios set xp = xp - e.xp_para_entrar where id = new.usuario_id;
  end if;
  return new;
end $$;
drop trigger if exists antes_de_inscribirse on public.inscripciones;
create trigger antes_de_inscribirse before insert on public.inscripciones
  for each row execute function public.antes_de_inscribirse();

-- Después de inscribirse: suma un cupo y, si es un torneo, misión "torneo" (+100 XP)
create or replace function public.al_inscribirse() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update public.eventos set cupos_ocupados = cupos_ocupados + 1 where id = new.evento_id;
  if (select tipo from public.eventos where id = new.evento_id) = 'torneo' then
    perform public.cumplir_mision(new.usuario_id, 'torneo', 'evento:' || new.evento_id);
  end if;
  return new;
end $$;
drop trigger if exists al_inscribirse on public.inscripciones;
create trigger al_inscribirse after insert on public.inscripciones
  for each row execute function public.al_inscribirse();

-- Al cancelar una inscripción: libera el cupo (el XP gastado en un sorteo no se devuelve)
create or replace function public.al_cancelar_inscripcion() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update public.eventos set cupos_ocupados = greatest(cupos_ocupados - 1, 0) where id = old.evento_id;
  return old;
end $$;
drop trigger if exists al_cancelar_inscripcion on public.inscripciones;
create trigger al_cancelar_inscripcion after delete on public.inscripciones
  for each row execute function public.al_cancelar_inscripcion();

-- Un voto "útil": aviso para el autor de la reseña
create or replace function public.al_votar_util() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  autor bigint;
  quien text;
  el_enlace text;
  el_texto text;
begin
  select usuario_id into autor from public.resenas where id = new.resena_id;
  select usuario into quien from public.usuarios where id = new.usuario_id;
  el_enlace := 'detalle-resena.html?id=' || new.resena_id;
  el_texto := '@' || quien || ' marcó tu reseña como útil.';
  -- Solo la primera vez: si quita el voto y lo vuelve a poner, no llega otro aviso igual
  if not exists (select 1 from public.notificaciones n where n.usuario_id = autor and n.tipo = 'voto_util' and n.enlace = el_enlace and n.texto = el_texto) then
    insert into public.notificaciones (usuario_id, tipo, texto, enlace) values (autor, 'voto_util', el_texto, el_enlace);
  end if;
  return new;
end $$;
drop trigger if exists al_votar_util on public.votos_util;
create trigger al_votar_util after insert on public.votos_util
  for each row execute function public.al_votar_util();

-- Avisos de cierre: a quien se inscribió a un evento que cierra inscripciones en las próximas 24 horas
-- (una vez por evento). Hay que ejecutarla cada cierto tiempo: por ejemplo con un cron de Vercel o de Supabase.
create or replace function public.crear_avisos_de_cierre() returns integer
language plpgsql security definer set search_path = public as $$
declare
  creados integer;
begin
  insert into public.notificaciones (usuario_id, tipo, texto, enlace)
  select i.usuario_id, 'cierre_inscripciones', e.titulo || ' cierra inscripciones pronto.', 'detalle-evento.html?id=' || e.slug
  from public.inscripciones i join public.eventos e on e.id = i.evento_id
  where e.cierre_inscripciones between now() and now() + interval '24 hours'
    and not exists (
      select 1 from public.notificaciones n
      where n.usuario_id = i.usuario_id and n.tipo = 'cierre_inscripciones' and n.enlace = 'detalle-evento.html?id=' || e.slug
    );
  get diagnostics creados = row_count;
  return creados;
end $$;

