  descripcion text not null,
  fecha_hora timestamptz not null,
  cierre_inscripciones timestamptz,
  organizador text not null,
  tipo_organizador text not null check (tipo_organizador in ('Marcas y organizadores', 'Desarrolladoras oficiales', 'SaveSlot')),
  cupos_ocupados integer not null default 0 check (cupos_ocupados >= 0),
  cupos_maximos integer check (cupos_maximos > 0),
